-- MaterialBook V1 — optimized schema (see docs/ARCHITECTURE.md §3 for rationale)
-- Conventions: BIGINT identity PKs, NUMERIC for qty/money, TIMESTAMPTZ, every FK column indexed.

CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ───────────────────────── A. Security ─────────────────────────

CREATE TABLE users (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name                VARCHAR(150) NOT NULL,
    mobile                   VARCHAR(20)  NOT NULL UNIQUE,
    email                    VARCHAR(150),
    password_hash            VARCHAR(255) NOT NULL,
    status                   VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    password_change_required BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_login_count       INT          NOT NULL DEFAULT 0,
    locked_until             TIMESTAMPTZ,            -- lockout is time-based, not a status
    last_login_at            TIMESTAMPTZ,
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at               TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX ux_users_email ON users (LOWER(email)) WHERE email IS NOT NULL;
CREATE TRIGGER trg_users_upd BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code   VARCHAR(50)  NOT NULL UNIQUE,
    role_name   VARCHAR(100) NOT NULL,
    description TEXT,
    is_system   BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE permissions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_code VARCHAR(100) NOT NULL UNIQUE,   -- e.g. MATERIAL_IN.CREATE
    module_code     VARCHAR(50)  NOT NULL,
    action_code     VARCHAR(30)  NOT NULL,
    description     VARCHAR(255)
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES roles(id),
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX ix_user_roles_role ON user_roles(role_id);

CREATE TABLE role_permissions (
    role_id       BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permissions(id),
    PRIMARY KEY (role_id, permission_id)
);
CREATE INDEX ix_role_permissions_perm ON role_permissions(permission_id);

CREATE TABLE user_permission_overrides (
    user_id       BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    permission_id BIGINT      NOT NULL REFERENCES permissions(id),
    effect        VARCHAR(5)  NOT NULL CHECK (effect IN ('ALLOW','DENY')),
    created_by    BIGINT REFERENCES users(id),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, permission_id)
);
CREATE INDEX ix_upo_perm ON user_permission_overrides(permission_id);

-- Refresh tokens: rotating, SHA-256 hex hash stored (never the raw token).
-- family_id enables reuse detection: replaying a rotated token revokes the whole family.
CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    family_id  UUID        NOT NULL,
    token_hash CHAR(64)    NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    user_agent VARCHAR(255),
    ip_address INET,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_refresh_tokens_user   ON refresh_tokens(user_id);
CREATE INDEX ix_refresh_tokens_family ON refresh_tokens(family_id);
CREATE INDEX ix_refresh_tokens_expiry ON refresh_tokens(expires_at);

