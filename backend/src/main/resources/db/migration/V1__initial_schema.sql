-- NEW (missing from the original design): supplier/client ledgers need payments.
-- direction PAID = we paid the party; RECEIVED = party paid us.
-- Ledger balance (positive = party owes us) =
--   opening_balance + SUM(OUT totals) - SUM(IN totals) + SUM(RECEIVED) - SUM(PAID)   [POSTED rows only]
CREATE TABLE party_payments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_number      VARCHAR(50)   NOT NULL UNIQUE,
    party_id            BIGINT        NOT NULL REFERENCES parties(id),
    payment_date        DATE          NOT NULL,
    direction           VARCHAR(8)    NOT NULL CHECK (direction IN ('PAID','RECEIVED')),
    amount              NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    payment_mode        VARCHAR(10) CHECK (payment_mode IN ('CASH','UPI','BANK','CHEQUE','OTHER')),
    reference_number    VARCHAR(100),
    remarks             TEXT,
    status              VARCHAR(10)   NOT NULL DEFAULT 'POSTED' CHECK (status IN ('POSTED','CANCELLED')),
    created_by          BIGINT        NOT NULL REFERENCES users(id),
    cancelled_by        BIGINT REFERENCES users(id),
    cancelled_at        TIMESTAMPTZ,
    cancellation_reason TEXT,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_pp_cancel_fields CHECK (
        (status = 'CANCELLED' AND cancelled_by IS NOT NULL AND cancelled_at IS NOT NULL AND cancellation_reason IS NOT NULL)
        OR (status = 'POSTED' AND cancelled_by IS NULL AND cancelled_at IS NULL))
);
CREATE INDEX ix_pp_party   ON party_payments(party_id, payment_date DESC) WHERE status = 'POSTED';
CREATE INDEX ix_pp_created ON party_payments(created_by);

