CREATE TABLE document_sequences (
    document_type VARCHAR(30) NOT NULL,     -- MIN, MOUT, EXP, PAY
    sequence_year INT         NOT NULL,
    last_number   BIGINT      NOT NULL DEFAULT 0,
    PRIMARY KEY (document_type, sequence_year)
);

-- Atomic, gap-tolerant, duplicate-free numbering: SELECT next_document_number('MIN', 2026) -> 'MIN-2026-00001'
-- The row lock taken by ON CONFLICT DO UPDATE serializes concurrent callers until their tx ends.
CREATE FUNCTION next_document_number(p_type VARCHAR, p_year INT) RETURNS VARCHAR AS $$
DECLARE n BIGINT;
BEGIN
    INSERT INTO document_sequences(document_type, sequence_year, last_number)
    VALUES (p_type, p_year, 1)
    ON CONFLICT (document_type, sequence_year)
    DO UPDATE SET last_number = document_sequences.last_number + 1
    RETURNING last_number INTO n;
    RETURN p_type || '-' || p_year || '-' || LPAD(n::TEXT, 5, '0');
END;
$$ LANGUAGE plpgsql;

