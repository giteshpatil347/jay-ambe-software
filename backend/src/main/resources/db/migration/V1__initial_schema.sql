-- ───────────────────────── C. Material transactions ─────────────────────────

CREATE TABLE material_transactions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_number  VARCHAR(50) NOT NULL UNIQUE,
    transaction_type    VARCHAR(3)  NOT NULL CHECK (transaction_type IN ('IN','OUT')),
    transaction_date    DATE        NOT NULL,
    party_id            BIGINT REFERENCES parties(id),
    challan_number      VARCHAR(100),
    vehicle_number      VARCHAR(50),
    driver_name         VARCHAR(150),
    remarks             TEXT,
    -- No total_quantity: items may use different units (TON/KG/PIECE), so a sum is meaningless.
    total_amount        NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    status              VARCHAR(10) NOT NULL DEFAULT 'POSTED' CHECK (status IN ('POSTED','CANCELLED')),
    version             BIGINT      NOT NULL DEFAULT 0,          -- optimistic locking
    created_by          BIGINT      NOT NULL REFERENCES users(id),
    updated_by          BIGINT REFERENCES users(id),
    cancelled_by        BIGINT REFERENCES users(id),
    cancelled_at        TIMESTAMPTZ,
    cancellation_reason TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_mt_party_for_in CHECK (transaction_type = 'OUT' OR party_id IS NOT NULL),
    CONSTRAINT ck_mt_cancel_fields CHECK (
        (status = 'CANCELLED' AND cancelled_by IS NOT NULL AND cancelled_at IS NOT NULL AND cancellation_reason IS NOT NULL)
        OR (status = 'POSTED' AND cancelled_by IS NULL AND cancelled_at IS NULL))
);
CREATE INDEX ix_mt_type_date   ON material_transactions(transaction_type, transaction_date DESC, id DESC);
CREATE INDEX ix_mt_party       ON material_transactions(party_id, transaction_date DESC) WHERE status = 'POSTED';
CREATE INDEX ix_mt_created_by  ON material_transactions(created_by);
CREATE TRIGGER trg_mt_upd BEFORE UPDATE ON material_transactions FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE material_transaction_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT        NOT NULL REFERENCES material_transactions(id) ON DELETE CASCADE,
    product_id     BIGINT        NOT NULL REFERENCES products(id),
    quantity       NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
    rate           NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (rate >= 0),
    -- Derived by the database so it can never disagree with quantity * rate.
    amount         NUMERIC(14,2) GENERATED ALWAYS AS (ROUND(quantity * rate, 2)) STORED,
    remarks        TEXT
);
CREATE INDEX ix_mti_transaction ON material_transaction_items(transaction_id);
CREATE INDEX ix_mti_product     ON material_transaction_items(product_id);

-- ───────────────────────── D. Inventory ─────────────────────────

-- One row per product (single stock location). It is the row-lock target for concurrency:
--   SELECT ... FROM stock_balances WHERE product_id = ANY(:ids) ORDER BY product_id FOR UPDATE
-- The CHECK makes negative stock impossible even if application code is buggy.
CREATE TABLE stock_balances (
    product_id BIGINT PRIMARY KEY REFERENCES products(id),
    quantity   NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    updated_at TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

CREATE FUNCTION create_stock_balance() RETURNS trigger AS $$
BEGIN
    INSERT INTO stock_balances(product_id) VALUES (NEW.id);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_products_balance AFTER INSERT ON products FOR EACH ROW EXECUTE FUNCTION create_stock_balance();

-- Append-only ledger. quantity_delta is signed: no CASE expression needed to sum stock.
-- Invariant: stock_balances.quantity = SUM(quantity_delta) per product (verified by a test).
CREATE TABLE stock_movements (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT        NOT NULL REFERENCES products(id),
    transaction_id      BIGINT REFERENCES material_transactions(id),
    transaction_item_id BIGINT REFERENCES material_transaction_items(id),
    movement_type       VARCHAR(15)   NOT NULL
        CHECK (movement_type IN ('OPENING','IN','OUT','REVERSAL_IN','REVERSAL_OUT')),
    quantity_delta      NUMERIC(14,3) NOT NULL,
    movement_date       DATE          NOT NULL,
    created_by          BIGINT        NOT NULL REFERENCES users(id),
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_sm_sign CHECK (
        (movement_type IN ('OPENING','IN','REVERSAL_IN')  AND quantity_delta > 0) OR
        (movement_type IN ('OUT','REVERSAL_OUT')          AND quantity_delta < 0)),
    CONSTRAINT ck_sm_tx CHECK (transaction_id IS NOT NULL OR movement_type = 'OPENING')
);
CREATE INDEX ix_sm_product_date ON stock_movements(product_id, movement_date, id);
CREATE INDEX ix_sm_transaction  ON stock_movements(transaction_id);
CREATE INDEX ix_sm_item         ON stock_movements(transaction_item_id);

