 'PRODUCT.VIEW','PRODUCT.CREATE','PRODUCT.UPDATE','PRODUCT.DELETE',
 'USER.VIEW','USER.CREATE','USER.UPDATE','USER.DEACTIVATE',
 'ROLE.VIEW','ROLE.CREATE','ROLE.UPDATE','ROLE.ASSIGN',
 'PERMISSION.VIEW','PERMISSION.MANAGE',
 'MATERIAL_IN.VIEW','MATERIAL_IN.CREATE','MATERIAL_IN.UPDATE','MATERIAL_IN.CANCEL','MATERIAL_IN.EXPORT',
 'MATERIAL_OUT.VIEW','MATERIAL_OUT.CREATE','MATERIAL_OUT.UPDATE','MATERIAL_OUT.CANCEL','MATERIAL_OUT.EXPORT',
 'INVENTORY.VIEW','INVENTORY.EXPORT',
 'EXPENSE.VIEW','EXPENSE.CREATE','EXPENSE.UPDATE','EXPENSE.CANCEL','EXPENSE.EXPORT',
 'EXPENSE_CATEGORY.MANAGE',
 'EMPLOYEE.VIEW','EMPLOYEE.CREATE','EMPLOYEE.UPDATE',
 'PARTY.VIEW','PARTY.CREATE','PARTY.UPDATE',
 'PAYMENT.VIEW','PAYMENT.CREATE','PAYMENT.CANCEL',
 'REPORT.VIEW','REPORT.EXPORT',
