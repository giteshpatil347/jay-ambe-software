-- V9: electricity usage quantity, MONTHLY salary payments, monthly employee salary with yearly revisions.

-- Electricity expenses record hours/days used instead of units x rate. Nullable: rows created before V9 have none.
-- usage_start/usage_end/units_consumed/unit_rate stay (old data) but are no longer written.
ALTER TABLE electricity_readings
    ADD COLUMN usage_quantity NUMERIC(10,2) CHECK (usage_quantity > 0);

-- Salary payment type WEEKLY becomes MONTHLY. The CHECK was auto-named in V1, so look it up instead of assuming its name.
DO $$
DECLARE
    c TEXT;
BEGIN
    FOR c IN SELECT conname FROM pg_constraint
             WHERE conrelid = 'salary_payments'::regclass AND contype = 'c'
               AND pg_get_constraintdef(oid) LIKE '%payment_type%'
    LOOP
        EXECUTE format('ALTER TABLE salary_payments DROP CONSTRAINT %I', c);
    END LOOP;
END $$;
UPDATE salary_payments SET payment_type = 'MONTHLY' WHERE payment_type = 'WEEKLY';
ALTER TABLE salary_payments
    ADD CONSTRAINT ck_sal_payment_type CHECK (payment_type IN ('MONTHLY','ADHOC','ADVANCE','SETTLEMENT'));

-- Employee salary is monthly. NOTE: existing values are only renamed, NOT converted from weekly to monthly.
ALTER TABLE employees RENAME COLUMN weekly_salary TO monthly_salary;

-- Source of truth for salary: one row per (employee, effective date). employees.monthly_salary mirrors the revision
-- that is current today (re-synced on every revision write; reads resolve by date, so future-dated rows need no scheduler).
CREATE TABLE employee_salary_revisions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id    BIGINT        NOT NULL REFERENCES employees(id),
    effective_from DATE          NOT NULL,
    monthly_salary NUMERIC(14,2) NOT NULL CHECK (monthly_salary >= 0),
    remarks        TEXT,
    created_by     BIGINT REFERENCES users(id),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (employee_id, effective_from)
);
CREATE INDEX ix_esr_employee_effective ON employee_salary_revisions(employee_id, effective_from DESC);

INSERT INTO employee_salary_revisions (employee_id, effective_from, monthly_salary)
SELECT id, COALESCE(joining_date, created_at::date), monthly_salary FROM employees;
